SELECT
    YEAR(DIFFERENTIATION_DATE) AS YEAR,
    
    # 분화된 연도별 가장 큰 대장균 크기
    (
        SELECT MAX(SIZE_OF_COLONY)
        FROM ECOLI_DATA B
        WHERE YEAR(B.DIFFERENTIATION_DATE) = YEAR(A.DIFFERENTIATION_DATE)
    ) - SIZE_OF_COLONY AS YEAR_DEV,
    ID
FROM ECOLI_DATA A
ORDER BY YEAR, YEAR_DEV