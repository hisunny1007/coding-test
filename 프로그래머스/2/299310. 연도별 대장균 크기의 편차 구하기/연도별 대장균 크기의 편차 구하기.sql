SELECT
    YEAR(DIFFERENTIATION_DATE) AS YEAR,
    # 분화된 연도별 가장 큰 대장균 크기 - 각 대장균 크기
    MAX(SIZE_OF_COLONY) OVER (
        PARTITION BY YEAR(DIFFERENTIATION_DATE)
    )
    - SIZE_OF_COLONY AS YEAR_DEV,
    ID
FROM ECOLI_DATA
ORDER BY YEAR, YEAR_DEV